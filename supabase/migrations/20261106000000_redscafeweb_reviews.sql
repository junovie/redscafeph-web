-- Reviews for www.redscafeph.com. Only the site's Worker reads/writes them, with the service role key.
create schema if not exists redscafeweb;

create table if not exists redscafeweb.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  location text not null default '',
  rating smallint not null check (rating between 1 and 5),
  comment text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  reply text not null default '',
  ip_hash text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists reviews_status_created on redscafeweb.reviews (status, created_at desc);
create index if not exists reviews_ip_created on redscafeweb.reviews (ip_hash, created_at);

alter table redscafeweb.reviews enable row level security;

revoke all on schema redscafeweb from anon, authenticated;
revoke all on all tables in schema redscafeweb from anon, authenticated;
grant usage on schema redscafeweb to service_role;
grant all on all tables in schema redscafeweb to service_role;
grant usage, select on all sequences in schema redscafeweb to service_role;

insert into redscafeweb.reviews (name, rating, status, created_at)
select 'Ryu', 5, 'approved', '2026-05-01T00:00:00Z'
where not exists (select 1 from redscafeweb.reviews where name = 'Ryu' and created_at = '2026-05-01T00:00:00Z');
